"""TankOS Self-Coding AI System — autonomous code maintenance and improvement.

Daily cycle:
1. System health scan → 2. Log analysis → 3. Code knowledge refresh
4. Improvement planning → 5. Code generation → 6. Testing
7. Git backup + deploy → 8. Learning memory update

All changes go through: review → test → approve → deploy → verify.
Rollback is automatic on failure.
"""

